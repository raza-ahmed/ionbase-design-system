/**
 * Every module that uses a client-only React API must carry `'use client'`,
 * and must still carry it after the build.
 *
 * Why this is a gate and not a convention: a missing directive cannot fail
 * here. It fails in the consumer's app, at import time, in whichever Server
 * Component happens to reach the module first — which is how 0.2.0 shipped
 * with no directives at all and nobody noticed until an RSC consumer had to
 * hand-write re-export shims to use the library.
 *
 * The required set is DERIVED from what each file imports, never hardcoded, so
 * a new hook-using component is covered the moment it is written. React's
 * server build is the authority on which APIs are client-only: `forwardRef`,
 * `memo` and `useId` exist there, so a forwardRef-only component is genuinely
 * usable from a Server Component and deliberately does NOT get a directive.
 */
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const PKG = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(PKG, 'src');
const DIST = join(PKG, 'dist');

/**
 * Named imports from these packages that throw in a Server Component.
 *
 * Verified against react@19's `react-server` export condition rather than
 * assumed: `forwardRef`, `memo` and `useId` resolve there, the rest do not.
 * Anything from react-aria / react-stately is a hook by construction.
 */
const SERVER_SAFE_REACT = new Set(['forwardRef', 'memo', 'useId', 'lazy']);
const CLIENT_PACKAGES =
  /^(react-aria|react-stately|@react-stately\/|@react-aria\/)/;

const DIRECTIVE = /^['"]use client['"];?/;

/** Source files to check: every .tsx/.ts under src/, minus generated tokens. */
function sourceFiles(dir, acc = []) {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) {
      // Generated by sync-tokens.mjs — plain data, never components.
      if (entry.name === 'tokens' || entry.name === 'styles') continue;
      sourceFiles(full, acc);
    } else if (/\.tsx?$/.test(entry.name)) {
      acc.push(full);
    }
  }
  return acc;
}

/**
 * The client-only APIs a file imports, if any.
 *
 * The leading `(?:[\w*\s]+,\s*)?` matters: every component here is written
 * `import React, { useRef } from 'react'`, and a pattern anchored on `import {`
 * silently matches none of them. That is not hypothetical — the first version
 * of this gate reported Checkbox, Radio and Toggle as hook-free.
 */
function clientApis(source) {
  const found = new Set();
  const importRe =
    /import\s+(type\s+)?(?:[\w*\s]+,\s*)?\{([^}]*)\}\s*from\s*['"]([^'"]+)['"]/g;

  for (const [, typeOnly, names, pkg] of source.matchAll(importRe)) {
    // `import type {…}` is erased before runtime, so it forces no boundary.
    if (typeOnly) continue;

    for (const raw of names.split(',')) {
      const trimmed = raw.trim();
      // Per-specifier `type` — `{ mergeProps, type AriaButtonProps }`.
      if (!trimmed || trimmed.startsWith('type ')) continue;
      const name = trimmed.split(/\s+as\s+/)[0].trim();

      if (CLIENT_PACKAGES.test(pkg)) {
        if (/^use[A-Z]/.test(name)) found.add(`${name} (${pkg})`);
      } else if (pkg === 'react') {
        if (
          (/^use[A-Z]/.test(name) || name === 'createContext') &&
          !SERVER_SAFE_REACT.has(name)
        ) {
          found.add(name);
        }
      }
    }
  }
  return found;
}

const errors = [];
let needed = 0;
let clean = 0;

for (const file of sourceFiles(SRC)) {
  const source = readFileSync(file, 'utf8');
  const apis = clientApis(source);
  const has = DIRECTIVE.test(source.trimStart());
  const rel = file.slice(SRC.length + 1);

  if (apis.size > 0) {
    needed++;
    if (!has) {
      errors.push(
        `${rel}: uses ${[...apis].join(', ')} but has no 'use client'.\n` +
          `    A Server Component importing this throws at import time.`,
      );
      continue;
    }

    // The build is the other half. tsc preserves a directive prologue, but
    // only when it is the first statement — and a silent no-op build has
    // shipped from this repo before.
    const out = join(DIST, rel.replace(/\.tsx?$/, '.js'));
    if (!existsSync(out)) {
      errors.push(`${rel}: no build output at ${out.slice(PKG.length + 1)}`);
    } else if (!DIRECTIVE.test(readFileSync(out, 'utf8').trimStart())) {
      errors.push(
        `${rel}: 'use client' is in the source but NOT in ${out.slice(PKG.length + 1)}.\n` +
          `    The build dropped it; consumers get nothing.`,
      );
    }
  } else {
    clean++;
    if (has) {
      errors.push(
        `${rel}: has 'use client' but imports no client-only API.\n` +
          `    Remove it — it forces a needless client boundary and pulls the\n` +
          `    module out of the server graph for no reason.`,
      );
    }
  }
}

if (errors.length) {
  console.error(`\nClient boundaries: ${errors.length} problem(s)\n`);
  for (const e of errors) console.error(`  ${e}\n`);
  process.exit(1);
}

console.log(
  `Client boundaries: ${needed} modules need 'use client' and have it in src and dist; ` +
    `${clean} stay server-renderable`,
);
