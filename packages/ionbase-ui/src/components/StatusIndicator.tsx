/**
 * StatusIndicator — a status as a shape, a colour and a word, together.
 *
 * THE TABLE'S COLOURED DOT, FIXED. A green dot and a red dot are the same
 * shape: to anyone who cannot tell the colours apart they say nothing, and
 * WCAG 1.4.1 fails. Here every status has its own shape, the colour is only
 * the second signal, and the word is always there. It is the general form of
 * what AgentActivity does for an agent's steps.
 *
 * QUIET BY DESIGN. The word keeps the text colour — only the shape is
 * coloured — so a column of statuses reads as text with markers, not as a
 * column of chips. A Badge is for a label that should stand out; this is for
 * the status of every row.
 *
 * NOT A LIVE REGION. It does not announce itself when it changes: in a table
 * of fifty rows that would be fifty announcements. Say what changed with a
 * Toast, or AgentRun's own announcements, where it matters.
 */
export const StatusIndicator = forwardRef<
  HTMLSpanElement,
  StatusIndicatorProps
>(({ intent = 'neutral', size = 'sm', children, className, ...rest }, ref) => (
  <span
    {...rest}
    ref={ref}
    data-intent={intent}
    className={[
      'ion-status',
      `ion-status--${intent}`,
      size !== 'sm' ? `ion-status--${size}` : '',
      className || '',
    ]
      .filter(Boolean)
      .join(' ')}
  >
    <span className="ion-status__icon">{GLYPHS[intent]}</span>
    <span className="ion-status__label">{children}</span>
  </span>
));

StatusIndicator.displayName = 'StatusIndicator';
